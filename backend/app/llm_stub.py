"""Заглушка LLM — протокол и чат."""

import random
import time

_CHAT_RESPONSES = [
    "🤖 [Заглушка] Здесь будет ответ LLM по вашему вопросу.",
    "📝 [Заглушка] Функция аналитики по транскрипту появится после интеграции модели.",
    "⚙️ [Заглушка] LLM-модуль в разработке.",
    "💡 [Заглушка] Задай вопрос по содержанию встречи — ответ придёт после подключения LLM.",
    "🔜 [Заглушка] Здесь будет чат-ассистент по итогам совещания.",
]


def fill_protocol(transcript: str, template_content: str | None = None) -> str:
    time.sleep(0.5)
    return (
        "📋 **Протокол совещания (ЗАГЛУШКА)**\n\n"
        "---\n\n"
        "**Тема совещания:** [будет заполнено LLM]\n"
        "**Дата:** [будет заполнено LLM]\n"
        "**Участники:** [будет заполнено LLM]\n\n"
        "### Повестка\n"
        "1. [пункт 1]\n"
        "2. [пункт 2]\n"
        "3. [пункт 3]\n\n"
        "### Решения\n"
        "- [решение 1]\n"
        "- [решение 2]\n\n"
        "### Задачи\n"
        "| № | Задача | Ответственный | Срок |\n"
        "|---|--------|---------------|------|\n"
        "| 1 | [задача] | [кто] | [когда] |\n\n"
        "---\n"
        "*Протокол сгенерирован в демо-режиме. Подключи LLM для реального заполнения.*"
    )


def chat_response(message: str, history: list[dict] | None = None) -> str:
    time.sleep(1)
    return random.choice(_CHAT_RESPONSES)
